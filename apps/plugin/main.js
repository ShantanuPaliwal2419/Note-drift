var LinkCheckerService = class {
  constructor(app, serpClient) {
    this.app = app;
    this.serpClient = serpClient;
  }
  async checkLinksInNote(file, maxLinks = 10) {
    const content = await this.app.vault.read(file);
    const linkRegex = /\[([^\]]+)\]\((https?:\/\/[^\s)]+)\)|(https?:\/\/[^\s)]+)/g;
    const linksToCheck = [];
    let match;
    while ((match = linkRegex.exec(content)) !== null) {
      if (linksToCheck.length >= maxLinks) break;
      const text = match[1] || "";
      const url = match[2] || match[3];
      if (url && !linksToCheck.some((l) => l.url === url)) {
        linksToCheck.push({ text, url });
      }
    }
    const deadLinks = [];
    for (const item of linksToCheck) {
      try {
        const res = await (0, import_obsidian9.requestUrl)({
          url: item.url,
          method: "HEAD",
          throw: false
        });
        if (res.status >= 400) {
          const candidates = await this.findCandidates(item.text, item.url);
          deadLinks.push({
            originalUrl: item.url,
            linkText: item.text,
            statusText: `${res.status} Not Found`,
            candidates
          });
        }
      } catch {
        const candidates = await this.findCandidates(item.text, item.url);
        deadLinks.push({
          originalUrl: item.url,
          linkText: item.text,
          statusText: "Connection failed",
          candidates
        });
      }
    }
    return deadLinks;
  }
  async findCandidates(linkText, originalUrl) {
    const query = linkText.trim() ? linkText.trim() : originalUrl;
    try {
      const res = await this.serpClient.search({
        engine: "google",
        q: query,
        num: 3
      });
      const candidates = [];
      for (const org of res.response.organic_results?.slice(0, 3) || []) {
        candidates.push({
          url: org.link,
          title: org.title,
          authority: org.link.includes("libfoo.dev") ? "Official" : "Community"
        });
      }
      return candidates;
    } catch {
      return [];
    }
  }
  async applyReplacements(file, replacements) {
    if (replacements.size === 0) return;
    let content = await this.app.vault.read(file);
    for (const [oldUrl, newUrl] of replacements.entries()) {
      content = content.split(oldUrl).join(newUrl);
    }
    await this.app.vault.modify(file, content);
  }
};

